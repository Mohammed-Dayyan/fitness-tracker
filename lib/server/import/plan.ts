type Delegate = {
  findMany(args: { where: JsonRecord }): Promise<JsonRecord[]>;
  createMany(args: { data: JsonRecord[] }): Promise<{ count: number }>;
  update(args: { where: JsonRecord; data: JsonRecord }): Promise<unknown>;
  deleteMany(args: { where: JsonRecord }): Promise<{ count: number }>;
};

export function delegate(db: Client, spec: KindSpec): Delegate {
  return (db as unknown as Record<string, Delegate>)[spec.model];
}

export function rowToJson(spec: KindSpec, row: JsonRecord): JsonRecord {
  const out: JsonRecord = { id: row.id };
  if (spec.date) out[spec.date.json] = dbToDate(row[spec.date.db] as Date);
  for (const [key, f] of Object.entries(spec.fields)) {
    const v = row[f.db];
    out[key] = v instanceof Date ? dbToDate(v) : (v ?? null);
  }
  return out;
}

function jsonToDb(spec: KindSpec, rec: JsonRecord, keys: string[]): JsonRecord {
  const out: JsonRecord = {};
  for (const key of keys) {
    if (key === "id") out.id = rec.id;
    else if (spec.date && key === spec.date.json) out[spec.date.db] = dateToDb(rec[key] as string);
    else {
      const f = spec.fields[key];
      const v = rec[key];
      out[f.db] = f.isDate && typeof v === "string" ? dateToDb(v) : v;
    }
  }
  if (spec.key === "exercise_sets" && keys.includes("exercise")) {
    out.exerciseKey = normalizeExerciseName(rec.exercise as string);
  }
  return out;
}

const same = (a: unknown, b: unknown) => (a ?? null) === (b ?? null);

function chunk<T>(items: T[], size: number): T[][] {
  const out: T[][] = [];
  for (let i = 0; i < items.length; i += size) out.push(items.slice(i, i + size));
  return out;
}

function missingNutrition(rec: JsonRecord): string[] {
  return ["calories", "protein_g", "carbs_g", "fat_g", "fiber_g"].filter((k) => rec[k] == null);
}

class KindState {
  readonly byId = new Map<string, JsonRecord>();
  readonly byDate = new Map<string, string>();
  constructor(readonly spec: KindSpec) {}

  put(rec: JsonRecord) {
    this.byId.set(rec.id as string, rec);
    if (this.spec.singletonPerDate && this.spec.date) this.byDate.set(rec[this.spec.date.json] as string, rec.id as string);
  }

  remove(id: string) {
    const rec = this.byId.get(id);
    if (!rec) return;
    this.byId.delete(id);
    if (this.spec.singletonPerDate && this.spec.date) {
      const d = rec[this.spec.date.json] as string;
      if (this.byDate.get(d) === id) this.byDate.delete(d);
    }
  }
}

type Item = {
  kind: KindKey;
  ref: string;
  value?: JsonRecord;
  errors?: string[];
  /** Nested exercise sets point at their workout's ref. */
  parentRef?: string;
  /** exercise_sets only: the record explicitly allows moving an existing set to another workout. */
  allowMove?: boolean;
};

/** A one-per-date record created earlier in this same import (not in the database yet). */
type PendingCreate = {
  o: RecordOutcome;
  rec: JsonRecord;
  index: number;
  inherited: Set<string>;
  baseFrom?: string;
};

