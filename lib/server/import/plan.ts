// Envelope parsing
// ---------------------------------------------------------------------------

export type EnvelopeResult = { ok: true; envelope: Envelope } | { ok: false; errors: string[] };

export function parseEnvelope(input: unknown): EnvelopeResult {
  if (input === null || typeof input !== "object" || Array.isArray(input)) {
    return { ok: false, errors: ["The import must be a JSON object."] };
  }
  const parsed = envelopeSchema.safeParse(input);
  if (!parsed.success) {
    const topKeys = Object.keys(envelopeSchema.shape);
    return {
      ok: false,
      errors: formatIssues(parsed.error, "", (path) => (path[0] === "delete" ? [...KIND_ORDER] : topKeys)),
    };
  }
  const envelope = parsed.data as Envelope;
  let total = 0;
  for (const k of KIND_ORDER) {
    total += envelope[k]?.length ?? 0;
    total += envelope.delete?.[k]?.length ?? 0;
    for (const w of k === "workouts" ? (envelope.workouts ?? []) : []) {
      const sets = (w as JsonRecord | null)?.sets;
      if (Array.isArray(sets)) total += sets.length;
    }
  }
  if (total > MAX_RECORDS_PER_IMPORT) {
    return {
      ok: false,
      errors: [`Too many records (${total}); split the import into batches of at most ${MAX_RECORDS_PER_IMPORT}.`],
    };
  }
  return { ok: true, envelope };
}

