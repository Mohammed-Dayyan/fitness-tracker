type Client = Db | Tx;
type JsonRecord = Record<string, unknown>;

export type Action = "create" | "update" | "unchanged" | "delete" | "rejected";

export type RecordOutcome = {
  kind: KindKey | "profile";
  /** Where the record sits in the payload, e.g. "food_entries[3]". */
  ref: string;
  action: Action;
  id: string | null;
  /** The ID was generated by the server (or will be, on confirm). */
  id_generated?: true;
  date?: string;
  /** Set when an update moves the record to another date. */
  previous_date?: string;
  /** Set when an update moves an exercise set to another workout. */
  previous_workout_id?: string;
  /** Fields whose stored value changes. */
  changes?: string[];
  errors?: string[];
  warnings?: string[];
  /** The record as it will be stored (create/update/unchanged). */
  record?: JsonRecord;
};

export type Plan = {
  outcomes: RecordOutcome[];
  deletes: { kind: KindKey; id: string }[];
  profile?: JsonRecord;
  writes: Record<KindKey, { updates: { id: string; data: JsonRecord }[]; creates: JsonRecord[] }>;
  warnings: string[];
  token: string;
};

