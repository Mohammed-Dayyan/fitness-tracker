/**
 * Computes what an import would do against the owner's current data, without
 * writing anything. The same function drives preview and commit, so a
 * confirmed import does exactly what its preview showed (or is refused).
 */
export async function buildPlan(db: Client, ownerId: string, env: Envelope): Promise<Plan> {
  const outcomes: RecordOutcome[] = [];
  const warnings: string[] = [];
  const writes = Object.fromEntries(KIND_ORDER.map((k) => [k, { updates: [], creates: [] }])) as unknown as Plan["writes"];
  const deletes: Plan["deletes"] = [];
  const defaultDate = env.date;
  // For the preview token: each outcome's prior stored state, and IDs minted here.
  const before = new Map<RecordOutcome, JsonRecord>();
  const generatedIds = new Set<string>();

  if (env.summary !== undefined) {
    warnings.push("The \"summary\" block was ignored: totals are always calculated from the stored entries.");
  }

  // 1. Validate each record independently -----------------------------------
  const schemas = new Map<string, z.ZodObject>();
  const schemaFor = (kind: KindKey, nestedSet = false) => {
    const key = `${kind}:${nestedSet}`;
    if (!schemas.has(key)) schemas.set(key, recordSchema(kind, { nestedSet }));
    return schemas.get(key)!;
  };

  const items: Record<KindKey, Item[]> = Object.fromEntries(KIND_ORDER.map((k) => [k, []])) as never;
  const nestedSets: Item[] = [];

  const validate = (kind: KindKey, ref: string, raw: unknown, nestedSet = false): Item => {
    const schema = schemaFor(kind, nestedSet);
    const r = schema.safeParse(raw);
    if (!r.success) return { kind, ref, errors: formatIssues(r.error, ref, () => Object.keys(schema.shape)) };
    const value = { ...(r.data as JsonRecord) };
    const allowMove = value.allow_move === true;
    delete value.allow_move;
    return { kind, ref, value, ...(allowMove ? { allowMove } : {}) };
  };

  for (const kind of KIND_ORDER) {
    (env[kind] ?? []).forEach((raw, i) => {
      const ref = `${kind}[${i}]`;
      const item = validate(kind, ref, raw);
      items[kind].push(item);
      if (kind !== "workouts") return;
      const rawSets = (raw as JsonRecord | null)?.sets;
      const sets = item.value ? (item.value.sets as unknown[] | undefined) : Array.isArray(rawSets) ? rawSets : undefined;
      if (item.value) delete item.value.sets;
      sets?.forEach((s, j) => {
        const setRef = `${ref}.sets[${j}]`;
        const nested = item.value
          ? validate("exercise_sets", setRef, s, true)
          : { kind: "exercise_sets" as const, ref: setRef, errors: [`${setRef}: its workout (${ref}) is invalid`] };
        nested.parentRef = ref;
        nestedSets.push(nested);
      });
    });
  }
  items.exercise_sets = [...nestedSets, ...items.exercise_sets];

  // 2. Explicit deletes --------------------------------------------------------
  const deleteIds: Record<KindKey, { ref: string; id: string }[]> = Object.fromEntries(
    KIND_ORDER.map((k) => [k, []]),
  ) as never;
  for (const kind of KIND_ORDER) {
    const seen = new Set<string>();
    (env.delete?.[kind] ?? []).forEach((raw, i) => {
      const ref = `delete.${kind}[${i}]`;
      const r = idSchema.safeParse(raw);
      if (!r.success) {
        outcomes.push({ kind, ref, action: "rejected", id: null, errors: formatIssues(r.error, ref) });
      } else if (seen.has(r.data)) {
        warnings.push(`${ref}: "${r.data}" is listed more than once; deleted once.`);
      } else {
        seen.add(r.data);
        deleteIds[kind].push({ ref, id: r.data });
      }
    });
  }

  // 3. Conflicting IDs inside the payload --------------------------------------
  for (const kind of KIND_ORDER) {
    const byId = new Map<string, Item[]>();
    for (const item of items[kind]) {
      const id = item.value?.id as string | undefined;
      if (id) byId.set(id, [...(byId.get(id) ?? []), item]);
    }
    const deleted = new Map(deleteIds[kind].map((d) => [d.id, d]));
    for (const [id, group] of byId) {
      if (group.length > 1) {
        const refs = group.map((g) => g.ref).join(", ");
        for (const g of group) {
          g.errors = [`${g.ref}: id "${id}" appears ${group.length} times in this import (${refs}); IDs must be unique per record type`];
          delete g.value;
        }
      }
      const del = deleted.get(id);
      if (del) {
        for (const g of group) {
          g.errors = [`${g.ref}: id "${id}" is also listed for deletion (${del.ref})`];
          delete g.value;
        }
        outcomes.push({ kind, ref: del.ref, action: "rejected", id, errors: [`${del.ref}: id "${id}" is also being created/updated in this import`] });
        deleteIds[kind] = deleteIds[kind].filter((d) => d !== del);
      }
    }
  }

  // 4. Load the existing rows these records can touch -------------------------
  const states = Object.fromEntries(KIND_ORDER.map((k) => [k, new KindState(KINDS[k])])) as Record<KindKey, KindState>;

  for (const kind of KIND_ORDER) {
    const spec = KINDS[kind];
    const st = states[kind];
    const ids = new Set<string>(deleteIds[kind].map((d) => d.id));
    const dates = new Set<string>();
    for (const item of items[kind]) {
      if (!item.value) continue;
      if (item.value.id) ids.add(item.value.id as string);
      if (spec.date) {
        const d = (item.value[spec.date.json] as string | undefined) ?? defaultDate;
        if (d) dates.add(d);
      }
    }
    if (kind === "workouts") {
      for (const s of items.exercise_sets) if (s.value?.workout_id) ids.add(s.value.workout_id as string);
    }
    const del = delegate(db, spec);
    if (kind === "targets") {
      // Small table, and creating a version needs the one in effect before it.
      (await del.findMany({ where: { ownerId } })).forEach((row) => st.put(rowToJson(spec, row)));
      continue;
    }
    for (const part of chunk([...ids], 5000)) {
      (await del.findMany({ where: { ownerId, id: { in: part } } })).forEach((row) => st.put(rowToJson(spec, row)));
    }
    if (spec.singletonPerDate && spec.date && dates.size) {
      const rows = await del.findMany({ where: { ownerId, [spec.date.db]: { in: [...dates].map(dateToDb) } } });
      rows.forEach((row) => st.put(rowToJson(spec, row)));
    }
  }

  // 5. Apply deletes to the in-memory state (children before parents) ----------
  const deletedWorkouts = new Set<string>();
  for (const kind of KIND_ORDER) {
    const spec = KINDS[kind];
    for (const d of deleteIds[kind]) {
      const existing = states[kind].byId.get(d.id);
      if (!existing) {
        outcomes.push({
          kind,
          ref: d.ref,
          action: "unchanged",
          id: d.id,
          warnings: [`${d.ref}: no ${spec.label} with id "${d.id}" exists (already deleted?)`],
        });
        continue;
      }
      states[kind].remove(d.id);
      if (kind === "workouts") deletedWorkouts.add(d.id);
      deletes.push({ kind, id: d.id });
      const o: RecordOutcome = {
        kind,
        ref: d.ref,
        action: "delete",
        id: d.id,
        date: spec.date ? (existing[spec.date.json] as string) : undefined,
      };
      before.set(o, existing);
      outcomes.push(o);
    }
  }
  // Exercise-set deletes run before workout deletes (FK order is irrelevant
  // thanks to ON DELETE CASCADE, but keeps the report readable).
  deletes.sort((a, b) => (a.kind === "exercise_sets" ? -1 : 0) - (b.kind === "exercise_sets" ? -1 : 0));

  // 6. Profile -------------------------------------------------------------------
  let profileWrite: JsonRecord | undefined;
  if (env.profile !== undefined) {
    const r = profileSchema.safeParse(env.profile);
    if (!r.success) {
      outcomes.push({
        kind: "profile",
        ref: "profile",
        action: "rejected",
        id: null,
        errors: formatIssues(r.error, "profile", () => Object.keys(PROFILE_FIELDS)),
      });
    } else {
      const row = await db.profile.findUnique({ where: { ownerId } });
      const current: JsonRecord = {};
      for (const [key, f] of Object.entries(PROFILE_FIELDS)) {
        const v = row ? (row as unknown as JsonRecord)[f.db] : key === "timezone" ? "Asia/Kolkata" : null;
        current[key] = v instanceof Date ? dbToDate(v) : (v ?? null);
      }
      const merged = { ...current, ...(r.data as JsonRecord) };
      // A birth date can't be in the future, judged on the owner's own calendar
      // day (their timezone), not the server's. Only checked when it is being set.
      const birthIn = (r.data as JsonRecord).birth_date;
      const localToday = todayInTimeZone(merged.timezone as string);
      if (typeof birthIn === "string" && birthIn > localToday) {
        outcomes.push({
          kind: "profile",
          ref: "profile",
          action: "rejected",
          id: null,
          errors: [`profile.birth_date: ${birthIn} is in the future (today is ${localToday} in ${merged.timezone})`],
        });
      } else {
        const changes = Object.keys(PROFILE_FIELDS).filter((k) => !same(merged[k], current[k]));
        const action: Action = !row ? "create" : changes.length ? "update" : "unchanged";
        if (action !== "unchanged") {
          profileWrite = {};
          for (const key of row ? changes : Object.keys(PROFILE_FIELDS)) {
            const f = PROFILE_FIELDS[key];
            const v = merged[key];
            profileWrite[f.db] = f.isDate && typeof v === "string" ? dateToDb(v) : v;
          }
        }
        const o: RecordOutcome = { kind: "profile", ref: "profile", action, id: null, changes: row ? changes : undefined, record: merged };
        before.set(o, current);
        outcomes.push(o);
      }
    }
  }

  // Workouts that existing sets currently belong to (for move messages); these
  // may not be among the workouts the payload mentions.
  const workoutLabels = new Map<string, string>();
  const describeWorkout = (id: string) => workoutLabels.get(id) ?? `"${id}"`;
  {
    const wanted = new Set<string>();
    for (const s of states.exercise_sets.byId.values()) wanted.add(s.workout_id as string);
    for (const w of states.workouts.byId.values()) {
      workoutLabels.set(w.id as string, `"${w.id}" (${[w.name, w.date].filter(Boolean).join(", ")})`);
      wanted.delete(w.id as string);
    }
    // Existing sets can be updated without repeating their workout_id, so the
    // workouts they currently belong to must be known (unless deleted here).
    const missing = [...wanted].filter((id) => !deletedWorkouts.has(id));
    if (missing.length) {
      const rows = await delegate(db, KINDS.workouts).findMany({ where: { ownerId, id: { in: missing } } });
      for (const row of rows) {
        const w = rowToJson(KINDS.workouts, row);
        states.workouts.put(w);
        workoutLabels.set(w.id as string, `"${w.id}" (${[w.name, w.date].filter(Boolean).join(", ")})`);
      }
    }
  }

  // 7. Records, in dependency order ----------------------------------------------
  const outcomeByRef = new Map<string, RecordOutcome>();
  // One-per-date kinds: records created earlier in this import, and the fields
  // earlier records in this import already set (to detect conflicting duplicates).
  const pending = new Map<string, PendingCreate>();
  const specifiedBy = new Map<string, Map<string, unknown>>();
  const noteSpecified = (kind: KindKey, id: string, v: JsonRecord, dateKey?: string) => {
    if (!KINDS[kind].singletonPerDate) return;
    const key = `${kind}:${id}`;
    const m = specifiedBy.get(key) ?? new Map<string, unknown>();
    for (const k of Object.keys(v)) if (k !== "id" && k !== dateKey) m.set(k, v[k]);
    specifiedBy.set(key, m);
  };
  const occupantDesc = (kind: KindKey, id: string) => {
    const p = pending.get(`${kind}:${id}`);
    return p ? `created earlier in this import by ${p.o.ref}` : `id "${id}"`;
  };
  for (const kind of KIND_ORDER) {
    const spec = KINDS[kind];
    const st = states[kind];
    const dateKey = spec.date?.json;
    const fieldKeys = Object.keys(spec.fields);

    for (const item of items[kind]) {
      const reject = (errors: string[], id: string | null = null): void => {
        const o: RecordOutcome = { kind, ref: item.ref, action: "rejected", id, errors };
        outcomes.push(o);
        outcomeByRef.set(item.ref, o);
      };
      if (!item.value) {
        reject(item.errors ?? [`${item.ref}: invalid record`]);
        continue;
      }
      const v = item.value;
      const givenId = (v.id as string | undefined) ?? null;

      if (item.parentRef) {
        const parent = outcomeByRef.get(item.parentRef);
        if (!parent || parent.action === "rejected") {
          reject([`${item.ref}: its workout (${item.parentRef}) was rejected`], givenId);
          continue;
        }
        v.workout_id = parent.id;
      }

      // Identify the existing record: by ID, or by date for one-per-day kinds.
      let existing: JsonRecord | undefined;
      if (givenId) existing = st.byId.get(givenId);
      else if (spec.singletonPerDate && dateKey) {
        const d = (v[dateKey] as string | undefined) ?? defaultDate;
        if (!d) {
          reject([`${item.ref}: no date. Give the record a "${dateKey}" or set a top-level "date".`]);
          continue;
        }
        const occupant = st.byDate.get(d);
        if (occupant) {
          // Another record in this import (or the database) already holds this date.
          const key = `${kind}:${occupant}`;
          const prior = specifiedBy.get(key);
          const conflicts = Object.keys(v).filter((k) => k !== "id" && k !== dateKey && prior?.has(k) && !same(prior.get(k), v[k]));
          if (conflicts.length) {
            reject([
              `${item.ref}: conflicts with an earlier ${spec.label} for ${d} in this import on ${conflicts.join(", ")}. Send one value per field per date, or put them in a single record.`,
            ]);
            continue;
          }
          const p = pending.get(key);
          if (p) {
            // Compatible duplicate of a record this import is creating: fold it in.
            const changedKeys: string[] = [];
            for (const k of Object.keys(v)) {
              if (k === "id" || k === dateKey) continue;
              if (!same(p.rec[k], v[k])) changedKeys.push(k);
              p.rec[k] = v[k];
              p.inherited.delete(k);
            }
            writes[kind].creates[p.index] = jsonToDb(spec, p.rec, ["id", ...(dateKey ? [dateKey] : []), ...fieldKeys]);
            p.o.warnings = (p.o.warnings ?? []).filter((w) => !w.includes("carried forward"));
            if (p.inherited.size) p.o.warnings.push(`${[...p.inherited].join(", ")} carried forward from the target set effective ${p.baseFrom}`);
            if (!p.o.warnings.length) delete p.o.warnings;
            noteSpecified(kind, occupant, v, dateKey);
            const merged: RecordOutcome = {
              kind,
              ref: item.ref,
              action: changedKeys.length ? "update" : "unchanged",
              id: occupant,
              date: d,
              record: p.rec,
              warnings: [`merged into ${p.o.ref}: both records are for ${d}, so one ${spec.label} is created with the combined values`],
            };
            if (changedKeys.length) merged.changes = changedKeys;
            if (p.o.id_generated) merged.id_generated = true;
            outcomes.push(merged);
            outcomeByRef.set(item.ref, merged);
            continue;
          }
          existing = st.byId.get(occupant);
        }
      }

      const recWarnings: string[] = [];
      const kindChecks = (rec: JsonRecord): string | null => {
        if (kind !== "exercise_sets") return null;
        if (!normalizeExerciseName(rec.exercise as string)) return `${item.ref}: exercise must contain letters or digits`;
        if (!states.workouts.byId.has(rec.workout_id as string)) {
          return deletedWorkouts.has(rec.workout_id as string)
            ? `${item.ref}: workout "${rec.workout_id}" is deleted in this import`
            : `${item.ref}: workout "${rec.workout_id}" does not exist`;
        }
        return null;
      };

      if (existing) {
        // ---- Update: omitted fields keep their stored value ----
        const id = existing.id as string;
        if (kind === "exercise_sets" && deletedWorkouts.has(existing.workout_id as string)) {
          reject([`${item.ref}: set "${id}" belongs to workout "${existing.workout_id}", which is deleted in this import`], id);
          continue;
        }
        let movedFrom: string | undefined;
        if (kind === "exercise_sets" && v.workout_id !== undefined && v.workout_id !== existing.workout_id) {
          if (!item.allowMove) {
            reject(
              [
                `${item.ref}: set "${id}" belongs to workout ${describeWorkout(existing.workout_id as string)}; importing it under workout ${describeWorkout(v.workout_id as string)} would move it. Add "allow_move": true to this set to confirm the move, or give it a new id to add a separate set.`,
              ],
              id,
            );
            continue;
          }
          movedFrom = existing.workout_id as string;
        }
        const merged: JsonRecord = { ...existing };
        for (const key of Object.keys(v)) if (key !== "id") merged[key] = v[key];

        const problem = kindChecks(merged);
        if (problem) {
          reject([problem], id);
          continue;
        }
        if (spec.singletonPerDate && dateKey && merged[dateKey] !== existing[dateKey]) {
          const occupant = st.byDate.get(merged[dateKey] as string);
          if (occupant && occupant !== id) {
            reject([`${item.ref}: another ${spec.label} (${occupantDesc(kind, occupant)}) already exists for ${merged[dateKey]}`], id);
            continue;
          }
        }
        const compared = dateKey ? [dateKey, ...fieldKeys] : fieldKeys;
        const changes = compared.filter((k) => !same(merged[k], existing[k]));
        if (kind === "food_entries" && missingNutrition(merged).length) {
          recWarnings.push(`missing nutrition: ${missingNutrition(merged).join(", ")}`);
        }
        if (movedFrom) {
          recWarnings.push(`moved from workout ${describeWorkout(movedFrom)} to workout ${describeWorkout(merged.workout_id as string)}`);
        }
        if (kind === "exercise_sets" && changes.includes("exercise") && normalizeExerciseName(merged.exercise as string) !== normalizeExerciseName(existing.exercise as string)) {
          recWarnings.push(`exercise changed from "${existing.exercise}" to "${merged.exercise}"`);
        }
        const o: RecordOutcome = {
          kind,
          ref: item.ref,
          action: changes.length ? "update" : "unchanged",
          id,
          date: dateKey ? (merged[dateKey] as string) : undefined,
          record: merged,
        };
        if (movedFrom) o.previous_workout_id = movedFrom;
        noteSpecified(kind, id, v, dateKey);
        if (changes.length) {
          o.changes = changes;
          if (dateKey && changes.includes(dateKey)) o.previous_date = existing[dateKey] as string;
          st.remove(id);
          st.put(merged);
          writes[kind].updates.push({ id, data: jsonToDb(spec, merged, changes) });
        }
        if (recWarnings.length) o.warnings = recWarnings;
        before.set(o, existing);
        outcomes.push(o);
        outcomeByRef.set(item.ref, o);
        continue;
      }

      // ---- Create ----
      const id = givenId ?? randomUUID();
      const rec: JsonRecord = { id };
      if (dateKey) {
        const d = (v[dateKey] as string | undefined) ?? defaultDate;
        if (!d) {
          reject([`${item.ref}: no date. Give the record a "${dateKey}" or set a top-level "date".`], givenId);
          continue;
        }
        rec[dateKey] = d;
        if (spec.singletonPerDate) {
          const occupant = st.byDate.get(d);
          if (occupant) {
            const early = pending.get(`${kind}:${occupant}`);
            reject(
              [
                early
                  ? `${item.ref}: ${early.o.ref} in this import already creates the ${spec.label} for ${d}. Put both in one record, or omit "id" here so they are combined.`
                  : `${item.ref}: a ${spec.label} already exists for ${d} with id "${occupant}". Use that id to update it, or omit "id".`,
              ],
              givenId,
            );
            continue;
          }
        }
      }

      // New target versions inherit omitted values from the version in effect.
      let base: JsonRecord | undefined;
      if (kind === "targets") {
        for (const t of st.byId.values()) {
          const from = t.effective_from as string;
          if (from <= (rec.effective_from as string) && (!base || from > (base.effective_from as string))) base = t;
        }
      }
      const inherited: string[] = [];
      for (const key of fieldKeys) {
        if (key in v) rec[key] = v[key];
        else if (base && key !== "notes" && base[key] != null) {
          rec[key] = base[key];
          inherited.push(key);
        } else rec[key] = null;
      }
      if (inherited.length) {
        recWarnings.push(`${inherited.join(", ")} carried forward from the target set effective ${base!.effective_from}`);
      }

      const missing = fieldKeys.filter((k) => spec.fields[k].required && rec[k] == null);
      if (missing.length) {
        reject([`${item.ref}: missing required field${missing.length > 1 ? "s" : ""}: ${missing.join(", ")}`], givenId);
        continue;
      }
      const problem = kindChecks(rec);
      if (problem) {
        reject([problem], givenId);
        continue;
      }
      if (kind === "food_entries" && missingNutrition(rec).length) {
        recWarnings.push(`missing nutrition: ${missingNutrition(rec).join(", ")}`);
      }

      st.put(rec);
      writes[kind].creates.push(jsonToDb(spec, rec, ["id", ...(dateKey ? [dateKey] : []), ...fieldKeys]));
      const o: RecordOutcome = {
        kind,
        ref: item.ref,
        action: "create",
        id,
        date: dateKey ? (rec[dateKey] as string) : undefined,
        record: rec,
      };
      if (spec.singletonPerDate) {
        pending.set(`${kind}:${id}`, { o, rec, index: writes[kind].creates.length - 1, inherited: new Set(inherited), baseFrom: base?.effective_from as string | undefined });
        noteSpecified(kind, id, v, dateKey);
      }
      if (!givenId) {
        o.id_generated = true;
        generatedIds.add(id);
      }
      if (recWarnings.length) o.warnings = recWarnings;
      outcomes.push(o);
      outcomeByRef.set(item.ref, o);
    }
  }

  return { outcomes, deletes, profile: profileWrite, writes, warnings, token: planToken(outcomes, before, generatedIds) };
}

/**
 * Fingerprint of what the plan will do and of the stored state it was planned
 * against. IDs minted during planning are blanked (they differ on every run);
 * everything else must match between preview and commit.
 */
function planToken(outcomes: RecordOutcome[], before: Map<RecordOutcome, JsonRecord>, generated: Set<string>): string {
  const blank = (rec: JsonRecord | undefined) =>
    rec
      ? Object.fromEntries(
          Object.entries(rec).map(([k, v]) => [k, typeof v === "string" && generated.has(v) ? null : v]),
        )
      : null;
  const canonical = outcomes.map((o) => [
    o.kind,
    o.ref,
    o.action,
    o.id && generated.has(o.id) ? null : o.id,
    o.date ?? null,
    o.changes ?? null,
    blank(o.record),
    blank(before.get(o)),
  ]);
  return createHash("sha256").update(JSON.stringify(canonical)).digest("hex").slice(0, 32);
}

// ---------------------------------------------------------------------------
// Applying
// ---------------------------------------------------------------------------

export async function applyPlan(tx: Tx, ownerId: string, plan: Plan): Promise<void> {
  for (const d of plan.deletes) {
    await delegate(tx, KINDS[d.kind]).deleteMany({ where: { ownerId, id: d.id } });
  }
  if (plan.profile) {
    await tx.profile.upsert({
      where: { ownerId },
      create: { ownerId, ...(plan.profile as object) },
      update: plan.profile,
    });
  }
  for (const kind of KIND_ORDER) {
    const del = delegate(tx, KINDS[kind]);
    // Updates first, in plan order, so a record moving off a date frees it
    // before a new one-per-day record is created there.
    for (const u of plan.writes[kind].updates) {
      await del.update({ where: { ownerId_id: { ownerId, id: u.id } }, data: u.data });
    }
    for (const part of chunk(plan.writes[kind].creates, 1000)) {
      await del.createMany({ data: part.map((c) => ({ ownerId, ...c })) });
    }
  }
}
